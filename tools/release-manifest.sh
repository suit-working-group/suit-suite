#!/usr/bin/env bash
# ============================================================================
# release-manifest.sh — write RELEASE-MANIFEST.md for the current suite state.
# ----------------------------------------------------------------------------
# Records, for every document PDF of the suite (the six generic documents and
# the four PDFs of each deposited edition), what was built and from what: the
# suite version (shared/suite-version.tex), the git commit and dirty state,
# the TeX engine and biber versions, and per PDF its SHA-256, its page count
# and the counts of undefined citations / references / localization keys
# found in its latexmk log. A later reader can thus prove which PDF (by hash)
# belongs to which release, and that it was built clean.
#
# Run it AFTER tools/suite-gates.sh passes and BEFORE the release commit: the
# commit recorded is therefore the parent of the release commit, and the
# release tag points to the commit that contains this manifest.
#
# Usage:
#   tools/release-manifest.sh            # writes RELEASE-MANIFEST.md
#   tools/release-manifest.sh --check    # exit 1 if a document PDF or its log is missing
# Exit: 0 ok; 1 missing PDF/log (--check) or error.
# ============================================================================
set -euo pipefail
cd "$(dirname "$0")/.."
MODE="${1:-write}"
OUT="RELEASE-MANIFEST.md"

ver=$(grep -oE '\\setloc\{suite-version\}\{[0-9.]+\}' shared/suite-version.tex \
      | grep -oE '[0-9]+\.[0-9]+\.[0-9]+' | head -1)
commit=$(git rev-parse --short=12 HEAD 2>/dev/null || echo "n/a")
dirty=$(git status --porcelain 2>/dev/null | grep -c . || true)
date_utc=$(date -u +%Y-%m-%dT%H:%MZ)
# SUIT_BIBER lets the maintainer name the biber binary actually used by the
# build (e.g. an extracted arm64 slice when the universal binary cannot run).
BIBER_BIN="${SUIT_BIBER:-biber}"
engine=$(pdflatex --version 2>/dev/null | head -1 || true)
biberv=$("$BIBER_BIN" --version 2>/dev/null | head -1 || true)
[ -n "$engine" ] || engine="pdflatex: version not available"
[ -n "$biberv" ] || biberv="biber: version not available"

# "<pdf>|<latexmk log>" — the aux dir is out/ next to each top-level .tex.
docs=(
  "suit-policy/policy-EN.pdf|suit-policy/out/policy-EN.log"
  "suit-policy/companion/policy-summary-EN.pdf|suit-policy/companion/out/policy-summary-EN.log"
  "suit-policy/argumentation/argumentation-policy-EN.pdf|suit-policy/argumentation/out/argumentation-policy-EN.log"
  "suit-solution/solution-EN.pdf|suit-solution/out/solution-EN.log"
  "suit-solution/summary/solution-summary-EN.pdf|suit-solution/summary/out/solution-summary-EN.log"
  "suit-solution/argumentation/argumentation-solution-EN.pdf|suit-solution/argumentation/out/argumentation-solution-EN.log"
)
for inst in instantiations/*/; do
  inst="${inst%/}"
  case "$inst" in *_TEMPLATE*) continue ;; esac
  [ -d "$inst/render" ] || continue
  for d in policy-EN policy-summary-EN solution-EN solution-summary-EN; do
    docs+=("$inst/render/$d.pdf|$inst/render/out/$d.log")
  done
done

sha256_of() {
  if command -v shasum >/dev/null 2>&1; then shasum -a 256 "$1" | awk '{print $1}';
  else sha256sum "$1" | awk '{print $1}'; fi
}
pages_of() {
  if command -v pdfinfo >/dev/null 2>&1; then pdfinfo "$1" 2>/dev/null | awk '/^Pages:/{print $2}';
  else echo "n/a"; fi
}
count_in_log() {  # $1 log, $2 pattern — logs may contain binary bytes: grep -a
  [ -f "$1" ] || { echo "n/a"; return; }
  grep -a -c -E "$2" "$1" || true
}

missing=0
rows=""
for entry in "${docs[@]}"; do
  pdf="${entry%%|*}"; log="${entry##*|}"
  if [ ! -f "$pdf" ]; then rows+="| \`$pdf\` | missing | — | — | — | — |"$'\n'; missing=1; continue; fi
  [ -f "$log" ] || missing=1
  sha=$(sha256_of "$pdf"); pages=$(pages_of "$pdf")
  uc=$(count_in_log "$log" "Citation .* undefined")
  ur=$(count_in_log "$log" "Reference .* undefined")
  ul=$(count_in_log "$log" "Undefined localization key")
  rows+="| \`$pdf\` | $pages | \`$sha\` | $uc | $ur | $ul |"$'\n'
done

if [ "$MODE" = "--check" ]; then
  if [ "$missing" -ne 0 ]; then echo "release-manifest: a document PDF or its log is missing"; exit 1; fi
  echo "release-manifest: all document PDFs and logs present"; exit 0
fi

{
  echo "# Release manifest — SUIT suite $ver"
  echo
  echo "Generated by \`tools/release-manifest.sh\` on $date_utc, after \`tools/suite-gates.sh\`, before the release commit."
  echo
  echo "| Fact | Value |"
  echo "|---|---|"
  echo "| Suite version (\`shared/suite-version.tex\`) | $ver |"
  echo "| Git commit at generation (parent of the release commit) | \`$commit\` |"
  echo "| Uncommitted changes at generation | $dirty file(s) (the release commit includes them) |"
  echo "| TeX engine | $engine |"
  echo "| Bibliography processor | $biberv |"
  echo
  echo "Per document: SHA-256 of the PDF as released, page count, and the counts of undefined citations, undefined references and undefined localization keys reported in its latexmk log (all must be 0)."
  echo
  echo "| Document | Pages | SHA-256 | Undef. citations | Undef. references | Undef. loc. keys |"
  echo "|---|---|---|---|---|---|"
  printf '%s' "$rows"
  echo
  echo "To verify a received PDF: \`shasum -a 256 <file>\` must match the row above for the release it claims to belong to."
} > "$OUT"
echo "release-manifest: wrote $OUT (suite $ver, commit $commit)"
[ "$missing" -eq 0 ] || { echo "release-manifest: WARNING — a document PDF or its log is missing (see rows)"; exit 1; }
